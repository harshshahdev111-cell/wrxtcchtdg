"""Generate an evaluation table directly from Django's offline scenario test run."""

import unittest
from pathlib import Path

from django.test.runner import DiscoverRunner


class EvalResult(unittest.TextTestResult):
    def __init__(self, *args, **kwargs):
        """Initialize unittest reporting and the list of evaluation-table outcomes."""
        super().__init__(*args, **kwargs)
        self.rows = []

    def addSuccess(self, test):
        """Record a passing scenario in both unittest output and the generated evaluation table."""
        super().addSuccess(test)
        self.rows.append((test.id(), "PASS", "All scenario assertions passed"))

    def addFailure(self, test, err):
        """Record an assertion failure and its explanation for the evaluation table."""
        super().addFailure(test, err)
        self.rows.append((test.id(), "FAIL", str(err[1])))

    def addError(self, test, err):
        """Record an unexpected test error and its explanation for the evaluation table."""
        super().addError(test, err)
        self.rows.append((test.id(), "ERROR", str(err[1])))

    def addSkip(self, test, reason):
        """Keep platform-specific scenarios visible without presenting them as passing."""
        super().addSkip(test, reason)
        self.rows.append((test.id(), "SKIP", reason))


class EvalRunner(DiscoverRunner):
    def get_resultclass(self):
        """Select the unittest result collector that also records evaluation outcomes."""
        return EvalResult

    def suite_result(self, suite, result, **kwargs):
        """Write the evaluation table from actual test results and return the failure count."""
        path = Path(__file__).resolve().parents[2] / "docs" / "eval-results.md"
        path.parent.mkdir(exist_ok=True)
        lines = [
            "# Offline evaluation results",
            "",
            "Generated by the test run. Scenario names describe asserted invariants.",
            "",
            "| Scenario | Expected | Actual | Pass/fail | Notes |",
            "|---|---|---|---|---|",
        ]
        for name, status, note in result.rows:
            scenario = name.rsplit(".", 1)[-1].removeprefix("test_").replace("_", " ")
            safe_note = note.replace("|", "/").replace("\n", " ")[:180]
            lines.append(
                f"| {scenario} | All invariant assertions pass | {safe_note} "
                f"| {status} | Offline model; PostgreSQL mocks |"
            )
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return super().suite_result(suite, result, **kwargs)
